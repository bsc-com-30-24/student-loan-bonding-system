import uuid
from decimal import Decimal

from django.conf import settings
from django.core.validators import MinValueValidator
from django.db import models

from bonds.models import Bond


class Agreement(models.Model):

    class Status(models.TextChoices):
        GENERATED = 'GENERATED', 'Generated'
        PENDING_SIGNATURE = 'PENDING_SIGNATURE', 'Pending Signature'
        SIGNED = 'SIGNED', 'Signed'
        COUNTERSIGNED = 'COUNTERSIGNED', 'Countersigned'

    agreement_number = models.UUIDField(
        primary_key=True,
        default=uuid.uuid4,
        editable=False
    )

    # Each bond can have only one agreement.
    # Nullable initially to preserve existing agreement records.
    bond = models.OneToOneField(
        Bond,
        on_delete=models.PROTECT,
        related_name='agreement',
        null=True,
        blank=True
    )

    student_id = models.CharField(max_length=50)

    loan_reference = models.CharField(max_length=100)

    # Copied from the application and the student profile when the
    # agreement is generated, so the downloadable template stays fixed.
    student_name = models.CharField(max_length=200, blank=True, default="")
    programme = models.CharField(max_length=120, blank=True, default="")
    academic_year_label = models.CharField(max_length=20, blank=True, default="")
    year_of_study = models.PositiveSmallIntegerField(null=True, blank=True)
    phone_number = models.CharField(max_length=20, blank=True, default="")
    tuition_amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=Decimal("0.00"),
        validators=[MinValueValidator(Decimal("0.00"))],
    )
    upkeep_amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=Decimal("0.00"),
        validators=[MinValueValidator(Decimal("0.00"))],
    )
    total_amount = models.DecimalField(
        max_digits=12,
        decimal_places=2,
        default=Decimal("0.00"),
        validators=[MinValueValidator(Decimal("0.00"))],
    )

    agreement_content = models.TextField()

    # The unsigned PDF generated by the system.
    generated_pdf = models.FileField(
        upload_to='agreements/pdfs/',
        null=True,
        blank=True
    )

    status = models.CharField(
        max_length=30,
        choices=Status.choices,
        default=Status.GENERATED
    )

    generated_at = models.DateTimeField(auto_now_add=True)

    # The student downloads the generated PDF, signs it and uploads it here.
    student_signed_document = models.FileField(
        upload_to='agreements/student_signed/',
        null=True,
        blank=True
    )

    # SHA-256 of the uploaded file, kept as tamper evidence.
    student_signed_document_sha256 = models.CharField(
        max_length=64,
        blank=True,
        default=''
    )

    student_signed_at = models.DateTimeField(
        null=True,
        blank=True
    )

    # The Loan Board Officer downloads the student-signed PDF, signs it
    # and uploads the final copy here.
    countersigned_document = models.FileField(
        upload_to='agreements/countersigned/',
        null=True,
        blank=True
    )

    countersigned_document_sha256 = models.CharField(
        max_length=64,
        blank=True,
        default=''
    )

    countersigned_by = models.ForeignKey(
        settings.AUTH_USER_MODEL,
        on_delete=models.SET_NULL,
        null=True,
        blank=True,
        related_name='countersigned_agreements'
    )

    board_countersigned_at = models.DateTimeField(
        null=True,
        blank=True
    )

    created_at = models.DateTimeField(auto_now_add=True)

    updated_at = models.DateTimeField(auto_now=True)

    def __str__(self):
        return str(self.agreement_number)